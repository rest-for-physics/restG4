constexpr std::array<double, 7> zenithDegrees = {0, 60, 89, 89.99, 89.99999, 89.9999999, 90};

class ScopedEngine {
   public:
    explicit ScopedEngine(CLHEP::HepRandomEngine* engine) : previous(CLHEP::HepRandom::getTheEngine()) {
        CLHEP::HepRandom::setTheEngine(engine);
    }
    ~ScopedEngine() { CLHEP::HepRandom::setTheEngine(previous); }

   private:
    CLHEP::HepRandomEngine* previous;
};

class TwoDrawEngine : public CLHEP::HepJamesRandom {
   public:
    std::array<double, 2> values;
    size_t draws = 0;
    TwoDrawEngine(double radial, double azimuth) : values{radial, azimuth} {}
    double flat() override { return values.at(draws++); }
};

class FixedCosmicsSource : public TRestGeant4ParticleSourceCosmics {
   public:
    G4ThreeVector incoming;
    void Update() override {
        RemoveParticles();
        TRestGeant4Particle particle;
        particle.SetParticleName("geantino");
        particle.SetEnergy(1250);  // keV
        particle.SetDirection({incoming.x(), incoming.y(), incoming.z()});
        AddParticle(particle);
    }
};

// Geant4 requires a physics-list instance before constructing a primary action.
// These tests generate vertices only; they do not transport particles.
class PositionPhysicsList : public G4VUserPhysicsList {
    void ConstructParticle() override { G4Geantino::GeantinoDefinition(); }
    void ConstructProcess() override {}
    void SetCuts() override {}
};

class ScopedDirectory {
   public:
    explicit ScopedDirectory(const std::filesystem::path& directory)
        : previous(std::filesystem::current_path()) {
        std::filesystem::current_path(directory);
    }
    ~ScopedDirectory() { std::filesystem::current_path(previous); }

   private:
    std::filesystem::path previous;
};

G4ThreeVector Incoming(double zenith, double azimuth) {
    // Use exactly horizontal directions for the 90-degree case, not cos(pi/2).
    const double mu = zenith == 90 ? 0 : std::cos(zenith * deg);
    const double s = std::sqrt(1 - mu * mu);
    return G4ThreeVector(s * std::cos(azimuth), -mu, s * std::sin(azimuth)).unit();
}

void CheckPosition(const G4ThreeVector& position, const G4ThreeVector& direction, double radius) {
    const double tolerance = 64 * std::numeric_limits<double>::epsilon() * radius;
    ASSERT_TRUE(std::isfinite(position.x()));
    ASSERT_TRUE(std::isfinite(position.y()));
    ASSERT_TRUE(std::isfinite(position.z()));
    EXPECT_NEAR(position.mag(), radius, tolerance);
    EXPECT_LE(position.dot(direction), tolerance);
}

// Only the energy/direction inputs are controlled. Positions and source-axis
// rotation are generated by the actual special-Cosmics production branch.
class CosmicPositionTest : public ::testing::Test {
   protected:
    SimulationManager simulation;
    G4RunManager runManager;
    FixedCosmicsSource* source = nullptr;
    std::unique_ptr<PrimaryGeneratorAction> generator;
    G4ThreeVector rotationAxis;
    double rotationAngle = 0;
    double radius = 0;

    void SetUp() override {
        const auto files = std::filesystem::path(__FILE__).parent_path().parent_path() / "files";
        ScopedDirectory directory(files);
        auto* metadata = new TRestGeant4Metadata("cosmic-position.rml");
        metadata->SetGdmlFilename(std::filesystem::absolute(metadata->GetGdmlFilename().Data()).string());
        simulation.SetRestMetadata(metadata);
        simulation.SetRestRun(new TRestRun());
        auto* detector = new DetectorConstruction(&simulation);
        runManager.SetUserInitialization(detector);
        runManager.DefineWorldVolume(detector->Construct());
        runManager.SetUserInitialization(new PositionPhysicsList);
        metadata->RemoveParticleSources();
        source = new FixedCosmicsSource;
        source->SetDirection(TVector3(0.3, -0.7, 0.2));
        metadata->AddParticleSource(source);
        simulation.InitializeOutputManager();
        G4Geantino::GeantinoDefinition();
        generator = std::make_unique<PrimaryGeneratorAction>(&simulation);
        const auto axis = source->GetDirection();
        const G4ThreeVector sourceAxis(axis.X(), axis.Y(), axis.Z());
        const G4ThreeVector reference(0, -1, 0);
        rotationAxis = reference.cross(sourceAxis);
        rotationAngle = sourceAxis.angle(reference);
        radius = metadata->GetGeant4PrimaryGeneratorInfo().GetSpatialGeneratorCosmicRadius();
        ASSERT_GT(radius, 0);
    }

    G4ThreeVector Rotate(G4ThreeVector value) const { return value.rotate(rotationAngle, rotationAxis); }
};

TEST_F(CosmicPositionTest, ProductionPositionsAndUniformDisk) {
    CLHEP::HepJamesRandom engine(563781);
    ScopedEngine engineScope(&engine);
    double worstRadiusError = 0;
    constexpr int samples = 10000;
    for (double zenith : zenithDegrees) {
        SCOPED_TRACE(zenith);
        std::array<int, 10> radialBins{};
        std::array<int, 12> angularBins{};
        std::array<int, 60> jointBins{};
        double sumR2 = 0, sumX = 0, sumY = 0, sumXY = 0;
        for (int i = 0; i < samples; ++i) {
            const double azimuth = twopi * (i + 0.371) / samples;
            source->incoming = Incoming(zenith, azimuth);
            const auto direction = Rotate(source->incoming).unit();
            G4Event event(i);
            generator->GeneratePrimaries(&event);
            const auto* vertex = event.GetPrimaryVertex();
            ASSERT_NE(vertex, nullptr);
            const auto position = vertex->GetPosition();
            ASSERT_TRUE(std::isfinite(position.mag()));
            CheckPosition(position, direction, radius);
            worstRadiusError = std::max(worstRadiusError, std::abs(position.mag() - radius));
            ASSERT_EQ(vertex->GetNumberOfParticle(), 1);
            const auto* particle = vertex->GetPrimary();
            EXPECT_NEAR((particle->GetMomentumDirection() - direction).mag(), 0, 1e-14);
            EXPECT_DOUBLE_EQ(particle->GetKineticEnergy() / keV, 1250);
            const auto axis = std::abs(direction.z()) < 0.9 ? G4ThreeVector(0, 0, 1) : G4ThreeVector(1, 0, 0);
            const auto e1 = direction.cross(axis).unit();
            const auto e2 = direction.cross(e1);
            const double x = position.dot(e1) / radius, y = position.dot(e2) / radius;
            const double r2 = x * x + y * y;
            ASSERT_LE(r2, 1 + 1e-13);
            ++radialBins[std::min(9, int(10 * r2))];
            const double phi = std::atan2(y, x) + pi;
            ++angularBins[std::min(11, int(12 * phi / twopi))];
            ++jointBins[12 * std::min(4, int(5 * r2)) + std::min(11, int(12 * phi / twopi))];
            sumR2 += r2;
            sumX += x;
            sumY += y;
            sumXY += x * y;
        }
        // r^2/R^2 and disk azimuth are uniform. Six-sigma bin bounds and
        // broad moment bounds avoid seed-sensitive statistical failures.
        for (int count : radialBins) EXPECT_NEAR(count, samples / 10., 6 * std::sqrt(samples * 0.1 * 0.9));
        for (int count : angularBins) EXPECT_NEAR(count, samples / 12., 6 * std::sqrt(samples * 11. / 144));
        EXPECT_NEAR(sumR2 / samples, 0.5, 0.02);
        EXPECT_NEAR(sumX / samples, 0, 0.03);
        EXPECT_NEAR(sumY / samples, 0, 0.03);
        EXPECT_NEAR(sumXY / samples, 0, 0.02);
        double chi2 = 0;
        for (int count : jointBins) {
            const double expected = samples / 60.;
            chi2 += (count - expected) * (count - expected) / expected;
        }
        EXPECT_LT(chi2, 140);  // 59 degrees of freedom; also checks radial/azimuthal independence.
    }
    EXPECT_NEAR(simulation.GetRestMetadata()
                    ->GetGeant4PrimaryGeneratorInfo()
                    .GetSpatialGeneratorCosmicSurfaceTermCm2(),
                pi * radius * radius / 100, 1e-12);
    RecordProperty("sampled_vertices", 7 * samples);
    RecordProperty("max_radius_error_mm", ::testing::PrintToString(worstRadiusError));
}

TEST_F(CosmicPositionTest, ProductionUsesHelperAndExactlyTwoPositionDraws) {
    for (double zenith : zenithDegrees) {
        for (double azimuth : {0., 0.37, 1.9, 4.2, 5.9}) {
            source->incoming = Incoming(zenith, azimuth);
            TwoDrawEngine engine(0.63, 0.27);
            ScopedEngine engineScope(&engine);
            G4Event event;
            generator->GeneratePrimaries(&event);
            EXPECT_EQ(engine.draws, 2u);
            engine.draws = 0;
            const auto& sampledDirection = source->GetParticles().at(0).GetMomentumDirection();
            const G4ThreeVector incoming(sampledDirection.X(), sampledDirection.Y(), sampledDirection.Z());
            const auto expected = Rotate(ComputeCosmicPosition(incoming.unit(), radius));
            EXPECT_NEAR((event.GetPrimaryVertex()->GetPosition() - expected).mag(), 0, 1e-12);
        }
    }
}

TEST(CosmicPosition, DiskEdgeRoundoff) {
    for (double radius : {0.01, 100., 1e6}) {
        for (double zenith : zenithDegrees) {
            for (double azimuth : {0., 0.37, 1.9, 4.2, 5.9}) {
                const auto direction = Incoming(zenith, azimuth);
                for (double radial : {0., 0.5, std::nextafter(1., 0.), 1.}) {
                    for (double phi : {0., 0.125, 0.37, 0.625, 0.9}) {
                        // Include the mathematical rim (u=1) as well as the
                        // largest representable uniform variate below it.
                        TwoDrawEngine engine(radial, phi);
                        ScopedEngine engineScope(&engine);
                        CheckPosition(ComputeCosmicPosition(direction, radius), direction, radius);
                        EXPECT_EQ(engine.draws, 2u);
                    }
                }
            }
        }
    }
}

